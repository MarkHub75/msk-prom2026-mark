"""Verify exact embedded slide pixels and, when present, native PowerPoint exports.

Adapted from OS cinematic-ppt-v1/final-production/scripts/verify-exports.py.
No product claims or slide copy are generated by this checker.
"""
from pathlib import Path
import argparse
import hashlib
import json
import posixpath
import zipfile
import xml.etree.ElementTree as ET
from PIL import Image, ImageChops, ImageStat

ROOT = Path(__file__).resolve().parents[1]
NS = {'p': 'http://schemas.openxmlformats.org/presentationml/2006/main',
      'a': 'http://schemas.openxmlformats.org/drawingml/2006/main',
      'r': 'http://schemas.openxmlformats.org/officeDocument/2006/relationships'}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--require-powerpoint', action='store_true')
    args = parser.parse_args()
    raw_notes = json.loads((ROOT / 'speaker-notes.json').read_text())
    scenes = raw_notes if isinstance(raw_notes, list) else raw_notes['slides']
    assert len(scenes) == 8
    deck = ROOT / 'exports/SafeWatch_Checkpoint_2026-10-24.pptx'
    pp_file = ROOT / 'evidence/powerpoint/report.json'
    pp = json.loads(pp_file.read_text(encoding='utf-8-sig')) if pp_file.exists() else None
    if args.require_powerpoint:
        assert pp is not None, 'Native PowerPoint report required'
    if pp is not None:
        assert pp['status'] == 'PASS' and pp['slideCount'] == 8
    checks = []
    with zipfile.ZipFile(deck) as archive:
        assert archive.testzip() is None
        presentation = ET.fromstring(archive.read('ppt/presentation.xml'))
        size = presentation.find('p:sldSz', NS)
        cx, cy = int(size.attrib['cx']), int(size.attrib['cy'])
        assert abs(cx / cy - 16 / 9) < 1e-6
        assert len(presentation.findall('p:sldIdLst/p:sldId', NS)) == 8
        for index, scene in enumerate(scenes, 1):
            source = ROOT / f'slides/slide-{index:02d}.png'
            expected = Image.open(source).convert('RGB')
            assert expected.size == (1920, 1080)
            slide = ET.fromstring(archive.read(f'ppt/slides/slide{index}.xml'))
            pics = slide.findall('.//p:pic', NS)
            assert len(pics) == 1 and not slide.findall('.//p:sp', NS)
            rid = pics[0].find('.//a:blip', NS).attrib['{' + NS['r'] + '}embed']
            rels = ET.fromstring(archive.read(f'ppt/slides/_rels/slide{index}.xml.rels'))
            target = next(item.attrib['Target'] for item in rels if item.attrib['Id'] == rid)
            media = posixpath.normpath(posixpath.join('ppt/slides', target))
            assert archive.read(media) == source.read_bytes(), f'Embedded PNG differs: {index}'
            transform = pics[0].find('.//a:xfrm', NS)
            assert transform.find('a:off', NS).attrib == {'x': '0', 'y': '0'}
            ext = transform.find('a:ext', NS).attrib
            assert abs(int(ext['cx']) - cx) <= 1 and int(ext['cy']) == cy
            note_xml = ET.fromstring(archive.read(f'ppt/notesSlides/notesSlide{index}.xml'))
            notes = ' '.join(item.text or '' for item in note_xml.findall('.//a:t', NS))
            assert scene['speech'] in notes and scene['title'] in notes
            assert scene.get('notes', '') in notes
            item = {'slide': index, 'size': list(expected.size), 'pptxEmbeddedPNGByteIdentical': True,
                    'pptxFullBleedOneImage': True, 'notesMatchInXML': True,
                    'additionalNotesMatchInXML': True,
                    'sourceSha256': hashlib.sha256(source.read_bytes()).hexdigest()}
            if pp is not None:
                native = Image.open(ROOT / f'evidence/powerpoint/slide-{index:02d}.png').convert('RGB')
                assert native.size == expected.size
                diff = ImageChops.difference(expected, native)
                mae = sum(ImageStat.Stat(diff).mean) / 3
                assert mae < 0.3, f'PowerPoint pixels differ materially on slide {index}: {mae}'
                assert pp['slides'][index - 1]['shapes'] == 1
                assert scene['speech'] in pp['slides'][index - 1]['notes']
                assert scene.get('notes', '') in pp['slides'][index - 1]['notes']
                item.update(powerPointRasterMeanAbsoluteChannelError=mae, notesMatchInPowerPoint=True)
            checks.append(item)
    report = {'status': 'PASS', 'slides': 8, 'checks': checks,
              'powerPointOpenRenderExport': 'PASS' if pp else 'NOT_RUN',
              'powerPointVersion': pp.get('version') if pp else None,
              'interactiveRepairDialogs': 'UNVERIFIED: unattended COM is not a manual dialog observation.',
              'editableInternalSlideObjects': False, 'notesEmbedded': True,
              'pptx': {'path': str(deck.relative_to(ROOT)), 'bytes': deck.stat().st_size,
                       'sha256': hashlib.sha256(deck.read_bytes()).hexdigest()}}
    out = ROOT / 'evidence/exports'
    out.mkdir(parents=True, exist_ok=True)
    (out / 'report.json').write_text(json.dumps(report, ensure_ascii=False, indent=2) + '\n')
    print(json.dumps({'status': 'PASS', 'slides': 8, 'powerPointOpenRenderExport': report['powerPointOpenRenderExport']}))


if __name__ == '__main__':
    main()
