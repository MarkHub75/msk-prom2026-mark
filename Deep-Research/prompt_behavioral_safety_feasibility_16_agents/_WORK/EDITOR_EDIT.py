# Resolve every relative Markdown target against the draft directory, then
# express that same destination from the report directory. URLs stay intact.
links = []
def relocate(match):
    label, target = match.group(1), match.group(2)
    parsed = urlsplit(target)
    if parsed.scheme or parsed.netloc or target.startswith('#'):
        return match.group(0)
    path, sep, anchor = target.partition('#')
    resolved = (src.parent / unquote(path)).resolve()
    relative = resolved.relative_to(root).as_posix()
    relocated = relative + (sep + anchor if sep else '')
    links.append({'from': target, 'to': relocated})
    return '[' + label + '](' + relocated + ')'

